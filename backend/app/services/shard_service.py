"""Shard coverage probing for Beike subway lines.

``probe_shards`` walks the per-station conditions generated by
``app.sources.beike_filters.build_line_shards`` and reports the scope total,
page capacity, de-duplicated union and per-shard missing reasons without
writing anything to the database. It is the validation step before running
the actual shard crawls.
"""

import asyncio
import math
import random
from collections.abc import Callable

from app.sources import beike_api
from app.sources.base import CaptchaRequiredError, SourceError

FetcherFactory = Callable[[str], beike_api.BeikeAPIFetcher]
DEFAULT_INTERVAL = (1.5, 3.0)


def normalize_page_size(value: int) -> int:
    return max(1, min(int(value), beike_api.MAX_LIMIT))


def _reachable(page_size: int) -> int:
    return beike_api.max_pages(page_size) * page_size


def crawl_commands(
    shards: list[dict],
    *,
    task_id: int = 1,
    page_size: int = beike_api.MAX_LIMIT,
    results: list[dict] | None = None,
) -> list[dict]:
    """Build one crawler command per station shard.

    ``--full-scan`` is only suggested when the probe proved the shard was fully
    fetched, because the crawler's ``suspect`` marking requires complete scope.
    """
    page_size = normalize_page_size(page_size)
    probed = {item["condition"]: item for item in results or []}
    commands: list[dict] = []
    for shard in shards:
        item = probed.get(shard["condition"])
        pages = 1
        full_scan = False
        if item is not None:
            if item.get("expected_pages"):
                pages = max(
                    1, min(int(item["expected_pages"]), beike_api.max_pages(page_size))
                )
            elif item.get("pages"):
                pages = max(1, int(item["pages"]))
            full_scan = bool(item.get("complete"))
        command = (
            f"python -m app.cli crawl --task-id {task_id} --line {shard['condition']}"
            f" --pages {pages} --transport api"
        )
        if full_scan:
            command += " --full-scan"
        commands.append(
            {
                "station": shard["name"],
                "condition": shard["condition"],
                "pages": pages,
                "full_scan": full_scan,
                "command": command,
            }
        )
    return commands


async def fetch_line_total(
    line_condition: str,
    *,
    city_code: str = "sz",
    sort: str = "newest",
    fetcher_factory: FetcherFactory | None = None,
) -> int | None:
    """Read the whole-line ``total`` once, as a denominator for coverage."""
    fetcher = (fetcher_factory or beike_api.BeikeAPIFetcher)(city_code)
    try:
        _, total = await fetcher.fetch_page(1, line=line_condition, sort=sort, limit=1)
    except CaptchaRequiredError:
        raise
    except SourceError:
        return None
    finally:
        await fetcher.close()
    return int(total) if total is not None else None


async def _probe_shard(
    fetcher: beike_api.BeikeAPIFetcher,
    shard: dict,
    *,
    pages: int,
    sort: str,
    page_size: int,
) -> tuple[dict, set[str]]:
    total: int | None = None
    page_count = 0
    fetched = 0
    codes: set[str] = set()
    error = None
    page_limit = (
        beike_api.max_pages(page_size) if pages <= 0 else min(pages, beike_api.max_pages(page_size))
    )
    try:
        for page in range(1, max(1, page_limit) + 1):
            drafts, page_total = await fetcher.fetch_page(
                page, line=shard["condition"], sort=sort, limit=page_size
            )
            page_count += 1
            fetched += len(drafts)
            codes.update(draft.source_listing_id for draft in drafts)
            if page_total is not None:
                total = int(page_total)
            if not drafts:
                break
            if total is not None and fetched >= total:
                break
            if len(drafts) < page_size:
                break
    except CaptchaRequiredError:
        raise
    except SourceError as exc:
        error = str(exc)

    reachable = _reachable(page_size)
    if error:
        complete = False
        missing_reason = f"请求失败：{error}"
    elif total is None:
        complete = False
        missing_reason = "接口未返回 total"
    elif fetched >= total:
        complete = True
        missing_reason = ""
    elif total > reachable:
        complete = False
        missing_reason = f"超过 offset 上限（最多 {reachable} 条）"
    else:
        complete = False
        missing_reason = f"未抓全（已抓 {fetched}/{total}）"

    result = {
        "station": shard["name"],
        "station_id": shard.get("station_id"),
        "condition": shard["condition"],
        "total": total,
        "pages": page_count,
        "fetched": fetched,
        "page_duplicates": fetched - len(codes),
        "expected_pages": math.ceil(total / page_size) if total else None,
        "complete": complete,
        "missing_reason": missing_reason,
        "error": error,
    }
    return result, codes


async def probe_shards(
    line: dict,
    shards: list[dict],
    *,
    city_code: str = "sz",
    pages: int = 1,
    sort: str = "newest",
    page_size: int = beike_api.MAX_LIMIT,
    line_total: int | None = None,
    fetcher_factory: FetcherFactory | None = None,
    interval: tuple[float, float] = DEFAULT_INTERVAL,
) -> dict:
    """Probe each shard, de-duplicating listings across shards by house code.

    ``pages=0`` means "fetch enough pages to cover each shard's ``total``",
    bounded by the API's 3000-item offset ceiling.
    """
    page_size = normalize_page_size(page_size)
    factory = fetcher_factory or beike_api.BeikeAPIFetcher
    fetcher = factory(city_code)
    seen: set[str] = set()
    results: list[dict] = []
    fetched_total = 0
    try:
        for index, shard in enumerate(shards):
            if index and interval[1] > 0:
                # One fetcher is reused for connection reuse and pacing, but the
                # next shard must not inherit the previous shard's feed cursor.
                await _sleep_random(interval)
            fetcher.reset_condition()
            result, codes = await _probe_shard(
                fetcher, shard, pages=pages, sort=sort, page_size=page_size
            )
            new_codes = codes - seen
            seen |= codes
            result["unique"] = len(new_codes)
            result["overlap"] = len(codes) - len(new_codes)
            results.append(result)
            fetched_total += result["fetched"]
    finally:
        await fetcher.close()

    scope_total = sum(item["total"] or 0 for item in results)
    summary = {
        "shards": len(results),
        "fetched": fetched_total,
        "unique": len(seen),
        "duplicates": fetched_total - len(seen),
        "scope_total": scope_total,
        "line_total": line_total,
        "coverage_vs_scope": round(len(seen) / scope_total, 4) if scope_total else None,
        "coverage_vs_line": round(len(seen) / line_total, 4) if line_total else None,
        "complete_shards": sum(1 for item in results if item["complete"]),
        "failed_shards": sum(1 for item in results if item["error"]),
        "pages_probed": sum(item["pages"] for item in results),
        "expected_pages": sum(item["expected_pages"] or 0 for item in results),
        "page_size": page_size,
        "partial": any(not item["complete"] for item in results),
    }
    return {
        "line": {
            "id": line.get("line_id"),
            "name": line.get("line_name"),
            "condition": line.get("line_condition"),
        },
        "shards": results,
        "summary": summary,
    }


async def _sleep_random(interval: tuple[float, float]) -> None:
    low, high = interval
    await asyncio.sleep(random.uniform(max(0.0, low), max(0.0, high)))
